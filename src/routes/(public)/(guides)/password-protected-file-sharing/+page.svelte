<h1>How to share a file with a password</h1>
<p>
	An OverDrive share link opens one version of a file. The recipient needs the link and the
	share password. They can open it in their browser without an OverDrive account.
</p>

<h2>Create a password-protected link</h2>
<ol>
	<li>Open your vault, find the file and choose <strong>Share link</strong> from its actions.</li>
	<li>Choose a share password of at least eight characters and enter it a second time.</li>
	<li>
		Set <strong>Expires in days</strong> if the file should be available for a limited time.
		Use <strong>Max downloads</strong> to limit the number of downloads the link can start.
	</li>
	<li>
		Select <strong>Create link</strong> and copy the link. Send the password through a separate
		channel, such as a phone call if you emailed the link.
	</li>
</ol>

<h2>What does the recipient see?</h2>
<p>
	The link first opens a password prompt. After the recipient selects <strong>Unlock</strong>,
	their browser uses the password to open the file key and display the filename. Choosing
	<strong>Decrypt &amp; download</strong> saves a readable copy on their device.
</p>

<h2>What if I upload a revised file?</h2>
<p>
	The original link still opens the version you shared. For example, if you replace a draft
	with a signed document, someone with the draft link still receives the draft. Create a new
	link to send them the signed version.
</p>

<h2>How do I stop sharing?</h2>
<p>
	Open <strong>Links</strong> in the vault, find the file and revoke its link. This stops
	further downloads through that link. A recipient who already saved a copy keeps it.
</p>
<p>
	Read <a href="/encrypted-cloud-storage">how OverDrive encrypts stored files</a> for more
	about the keys behind a share link.
</p>
